import assert from 'node:assert/strict';
import {mapRows,filterMapRows,mapPointCollection,localityReference,validPoint,selectedMapID,mapSelectionURL,surveyMode,surveyHref} from '../js/finfolk-next/site/web-main/app/(atlas)/atlas/explore-model.js';
import {atlasBeaches} from './fixtures/nextjs-atlas.mjs';
import {resolveModel,bindPageClient} from '../js/finfolk-next/packages/edge/page-models.js';
const listings=[{id:'school',name:'Ocean School',country:'Australia',state:'NSW',locality:'Bondi Beach',category:'School'},{id:'unknown',name:'Unmapped School',country:'Australia',state:'VIC',locality:'Unknown'},{id:'overseas',name:'Foreign School',country:'New Zealand',locality:'Bondi Beach'}],events=[{id:'meetup',document:{title:'Shore meetup',location:'Bondi Beach'},starts_at:'2030-01-01T00:00:00Z'}],rows=mapRows(atlasBeaches,listings,events,['bondi','not-published']);
assert.equal(rows.length,7);
assert.equal(rows.filter(r=>r.kind==='people').length,1);
assert.equal(filterMapRows(rows,{category:'business'}).length,3);
assert.equal(filterMapRows(rows,{category:'business',query:'ocean'}).length,1);
assert.equal(filterMapRows(rows,{bounds:{contains:p=>p[0]===145}}).length,4);
assert.equal(rows.find(r=>r.sourceId==='unknown').point,undefined);
assert.equal(rows.find(r=>r.sourceId==='overseas').point,undefined);
assert.match(rows.find(r=>r.sourceId==='school').reference,/premises unconfirmed/);
assert.equal(mapPointCollection(rows).features.find(f=>f.properties.id==='spot:bondi').properties.count,4);
assert.equal(mapPointCollection(rows).features.reduce((n,f)=>n+f.properties.count,0),5);
assert.equal(localityReference('Bondi Beach','VIC',atlasBeaches),null);
assert.equal(localityReference('Unknown','',atlasBeaches),null);
assert.equal(localityReference('Bondi Beach','',{...atlasBeaches,beaches:[...atlasBeaches.beaches,{...atlasBeaches.beaches[0],id:'duplicate'}]}),null);
for(const p of [[181,0],[0,86],[NaN,1],[1],null,['145',-38]])assert.equal(validPoint(p),false);
assert.equal(surveyMode(new URLSearchParams('mode=survey')),true);
assert.equal(surveyMode(new URLSearchParams('depth=20')),true);
assert.equal(surveyMode(new URLSearchParams('site=bondi')),false);
assert.equal(surveyHref('bondi'),'/map?mode=survey&site=bondi');
assert.equal(selectedMapID(new URLSearchParams('listing=school')),'business:school');
assert.equal(mapSelectionURL('https://example.test/map?site=bondi&category=business',rows.find(r=>r.sourceId==='school')),'/map?category=business&listing=school');
assert.equal(mapSelectionURL('https://example.test/map?site=bondi&category=business',null),'/map?category=business');
assert.deepEqual(resolveModel('map','listings',{query:{offset:50}}).values,{offset:50});
assert.deepEqual(resolveModel('map','listing',{id:'school'}).values,{id:'school'});
assert.doesNotThrow(()=>bindPageClient('map',{call(){}}).call('publicDirectory',{}));
assert.throws(()=>bindPageClient('map',{call(){}}).call('myCheckins',{}),/Undeclared page/);
console.log('EXPLORE_MODEL_PASS: published data only, locality uncertainty, unknown and overseas positions, co-located entities, visibility, filters, shared links and declared public reads.');
