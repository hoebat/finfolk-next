(ns finfolkdb.schema.directory-contracts
  "Directory payloads and native operation declarations shared by server, backbone and UI types.")
(def S {:type "string"})
(def U {:type "string" :format "uuid"})
(def B {:type "boolean"})
(def N {:type "integer"})
(def E {:type "object" :additionalProperties false})
(defn object [properties required] {:type "object" :additionalProperties false :properties properties :required required})
(defn array-of [schema] {:type "array" :items schema})
(def CATEGORIES ["School" "Instructor" "Business" "Club" "Group" "Freediver"])
(def DOCUMENT (object {:name S :category {:type "string" :enum CATEGORIES} :state S :country S :locality S :description S
                      :website S :image S :sources (array-of S) :socials (array-of S)} ["name" "category" "state" "sources" "socials"]))
(def PUBLIC (object (merge (:properties DOCUMENT) {:id U :managed B :reviewedAt {:type ["number" "null"]}})
                    ["id" "name" "category" "state" "country" "locality" "description" "website" "image" "sources" "socials" "managed" "reviewedAt"]))
(def OWNED (object {:id U :document (assoc DOCUMENT :additionalProperties true) :status S :revision N
                    :owner_id {:type ["string" "null"]} :role {:type ["string" "null"]} :notes S :outreach S}
                   ["id" "document" "status" "revision" "owner_id" "role"]))
(def CLAIM (object {:id U :listing_id U :user_id U :state S :challenge S :expires_at {:type "number"}} ["id" "state" "challenge" "expires_at"]))
(def ID (object {:id U} ["id"]))
(def SAVE (object {:id U :revision N :document DOCUMENT :status S :notes S :outreach S :revokeOwner B} ["id" "revision" "document"]))
(defn op [action request result write & [public]]
  {:rpc (str "native_directory_" (.replace action "-" "_")) :arguments ["$actor" "$verified" "$values"]
   :actor "server" :action action :request request :result result :write write :public (boolean public) :not-found "Page unavailable."})
(def OPERATIONS
  {"publicDirectory" (op "public-list" (object {:q S :category S :state S :locality S :offset S :site S} [])
                          (object {:listings (array-of PUBLIC) :next {:type ["integer" "null"]}} ["listings" "next"]) false true)
   "publicDirectoryDetail" (op "public-detail" ID PUBLIC false true)
   "directoryMine" (op "mine" E (object {:admin B :listings (array-of OWNED) :claims (array-of CLAIM)} ["admin" "listings" "claims"]) false)
   "directoryCreate" (op "owner-create" (object {:requestId U :document DOCUMENT} ["requestId" "document"]) (object {:id U :status S} ["id" "status"]) true)
   "directoryOwnerSave" (op "owner-save" SAVE ID true)
   "pageAccess" (op "page-access" ID (object {:role S :admins (array-of (object {:id U :name S} ["id" "name"]))
                                             :invites (array-of (object {:id U :expiresAt {:type "number"}} ["id" "expiresAt"]))} ["role" "admins" "invites"]) false)
   "directoryClaim" (op "claim" ID (object (select-keys (:properties CLAIM) [:id :challenge :expires_at]) ["id" "challenge" "expires_at"]) true)
   "directoryReport" (op "report" (object {:id U :message S} ["id" "message"]) E true)
   "directoryAdmin" (op "admin" E (object {:listings (array-of OWNED) :claims (array-of CLAIM)
                                          :reports (array-of {:type "object" :additionalProperties true}) :runs (array-of {:type "object" :additionalProperties true})
                                          :audit (array-of {:type "object" :additionalProperties true})} ["listings" "claims" "reports" "runs" "audit"]) false)
   "directoryDiscover" (assoc (op "discovery-start"
      (object {:region S :category {:type "string" :enum CATEGORIES} :state S :country S :seed S} ["region" "category" "state"])
      (object {:id U :count N :state {:type "string" :enum ["running" "complete" "failed"]} :error S} ["id" "count" "state" "error"]) true)
      :effect "directory-discovery" :completion-rpc "native_directory_discovery_finish")
   "directoryMerge" (op "merge" (object {:source U :target U} ["source" "target"]) ID true)
   "directoryAdminSave" (op "admin-save" (assoc SAVE :required ["document" "status"]) ID true)
   "directoryClaimReview" (op "claim-review" (object {:id U :approve B :evidence S} ["id" "approve"]) E true)
   "directoryReportResolve" (op "report-resolve" ID E true)
   "pageInvite" (op "invite-create" ID (object {:id U :token S :expiresAt {:type "number"}} ["id" "token" "expiresAt"]) true)
   "pageInviteRedeem" (op "invite-redeem" (object {:token S} ["token"]) ID true)
   "pageInviteRevoke" (op "invite-revoke" (object {:id U :invite U} ["id" "invite"]) E true)
   "pageAdminRemove" (op "admin-remove" (object {:id U :user U} ["id" "user"]) E true)})
