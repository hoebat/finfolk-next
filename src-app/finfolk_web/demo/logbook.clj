(ns finfolk-web.demo.logbook (:require [lang.core :as l]))
(l/script :js {:import [["./backbone/backbone.mjs" :as [* backbone]]]})
(def.js state {"actor" "alice" "model" nil "session" nil "last" nil "events" [] "unsubscribe" nil "mutation" nil})
(defn.js el [selector] (return (document.querySelector selector)))
(defn.js inspect []
  (var model (. -/state model))
  (var frame (. model.node.spaces [model.space]))
  (var groups (and frame frame.state.page.groups))
  (:= (. (-/el "#inspector") textContent)
      (JSON.stringify {"actor" (. -/state actor) "kind" model.kind
                       "space" model.space "groups" (Object.keys (or groups {}))
                       "session" (. -/state session)
                       "cached" (:? (. -/state session) (model.read "session" {"id" (. -/state session)}) nil)
                       "last" (. -/state last) "mutation" (. -/state mutation) "events" (. -/state events)} nil 2)))
(defn.js ^{:- [:async]} transport [operation values]
  (var response (await (fetch "/rpc" {"method" "POST" "headers" {"Content-Type" "application/json" "X-Demo-Token" (. (document.querySelector "meta[name=demo-token]") content)}
    "body" (JSON.stringify {"actor" (. -/state actor) "operation" operation "values" values})})))
  (var data (await (response.json)))
  (. (. -/state events) (push {"operation" operation "status" response.status "code" (and data data.code) "error" (and data data.error) "time" (Date.now)}))
  (when (not response.ok) (throw (Object.assign (new Error data.error) {"code" data.code "status" response.status})))
  (return data))
(defn.js switchActor []
  (when (. -/state unsubscribe) ((. -/state unsubscribe)))
  (when (. -/state model) (. (. -/state model) (close)))
  (:= (. -/state actor) (. (-/el "#actor") value))
  (:= (. -/state model) (backbone.createBackbone (. -/state actor) -/transport {}))
  (. (. -/state model) (subscribe "saveSession" {} (fn [value] (:= (. -/state mutation) value) (-/inspect))))
  (:= (. -/state events) [])
  (:= (. (-/el "#result") textContent) "Actor selected. Refresh the session to check ownership.")
  (when (. -/state session)
    (:= (. -/state unsubscribe) (. (. -/state model) (subscribe "session" {"id" (. -/state session)} (fn [value] (:= (. -/state last) value) (-/inspect))))))
  (-/inspect))
(defn.js ^{:- [:async]} run [kind]
  (try
    (:= (. (-/el "#status") textContent) "Working…")
    (var model (. -/state model))
    (when (== kind "save")
      (var result (await (model.call "saveSession" {"notes" (. (-/el "#notes") value) "visibility" "public" "photos" ["untrusted"]})))
      (:= (. -/state session) result.id)
      (when (. -/state unsubscribe) ((. -/state unsubscribe)))
      (:= (. -/state unsubscribe) (model.subscribe "session" {"id" result.id} (fn [value] (:= (. -/state last) value) (-/inspect)))))
    (when (== kind "reject") (await (model.call "saveSession" {"invalidSite" true})))
    (when (. -/state session)
      (var row (await (model.call "session" {"id" (. -/state session)})))
      (:= (. (-/el "#result") textContent) (JSON.stringify row nil 2)))
    (:= (. (-/el "#status") textContent) "Done. Inspect the persisted result and live model state below.")
    (catch error (:= (. (-/el "#status") textContent) (+ "Rejected: " error.message)))
    (finally (-/inspect))))
(defrun.js boot
  (-/switchActor)
  (. (-/el "#actor") (addEventListener "change" -/switchActor))
  (. document (addEventListener "click" (fn [event]
    (when event.target.dataset.operation (-/run event.target.dataset.operation)))))
  (. window (addEventListener "beforeunload" (fn [] (. (. -/state model) (close))))))
