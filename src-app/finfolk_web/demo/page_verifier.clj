(defn.js ^{:- [:async]} execute [input handles]
  (var trace []) (var states []) (var model nil) (var subscriptions []) (var caches [])
  (try
    (:= handles.trace trace)
    (var values (or input.inputs {}))
    (when (== input.kind "resolve")
      (return {"result" (pages.resolveModel input.page input.member values (or input.payload {})) "trace" []}))
    (when (== input.kind "model")
      (var resolved (pages.resolveModel input.page input.member values (or input.payload {})))
      (var entry (. (pages.definition input.page) ["models"] [input.member]))
      (when entry.sdk
        (var args (pages.sdkArgs entry.sdk resolved.values))
        (when (. args (some (fn [v] (return (=== v undefined)))))
          (throw (new Error "Missing SDK argument; supply model values in payload")))))
    (when (not (. ["logbook" "logbook-editor"] (includes input.page)))
      (return {"blocked" "Live adapter is available for logbook and logbook-editor only"}))
    (when (or (and (== input.kind "model") (not (. ["session" "profile" "ensure"] (includes input.member))))
              (and (== input.kind "action") (not (== input.member "save"))))
      (return {"blocked" "This model/action has no native fixture adapter"}))
    (when (and (== input.kind "action") input.payload input.payload.id)
      (return {"blocked" "The native slice supports creating sessions, not editing existing ones"}))
    (var response (await (fetch (+ -/origin "/"))))
    (var html (await (response.text)))
    (var token (. html (match (new RegExp "name=demo-token content='([^']+)'"))))
    (when (not token) (throw (new Error "Start make demo-logbook before live verification")))
    (var actor (or input.actor "alice"))
    (when (not (. ["alice" "bob"] (includes actor))) (throw (new Error "Unknown fixture actor")))
    (var uid (:? (== actor "alice") "20000000-0000-0000-0000-000000000001" "20000000-0000-0000-0000-000000000002"))
    (when (and handles.model (not (== handles.actor actor))) (handles.model.close) (:= handles.model nil))
    (:= model (or handles.model (backbone.createBackbone uid
      (async (fn [operation payload]
        (var response (await (fetch (+ -/origin "/rpc")
          {"method" "POST" "headers" {"Content-Type" "application/json" "X-Demo-Token" (. token [1])}
           "body" (JSON.stringify {"actor" actor "operation" operation "values" payload})})))
        (var body (await (response.json)))
        (. handles.trace (push {"operation" operation "inputs" payload "status" response.status}))
        (when (not response.ok) (throw (Object.assign (new Error body.error) {"code" body.code "status" response.status})))
        (return body))) {})))
    (:= handles.actor actor) (:= handles.model model)
    (var invoke (async (fn [operation args]
      (. subscriptions (push (model.subscribe operation args
        (fn [state] (. states (push {"operation" operation "inputs" args "state" (Object.assign {} state)}))))))
      (try (return (await (model.call operation args)))
        (catch error (throw error))
        (finally
          (var cached (model.read operation args))
          (. caches (push {"operation" operation "inputs" args "present" (not (=== cached undefined))
                           "value" (:? (=== cached undefined) nil cached)})))))))
    (var client {"user" {"uid" uid}
      "profile" (fn [target] (return (invoke "profile" {"target" target})))
      "ensureProfile" (fn [] (return (invoke "me" {})))
      "get" (async (fn [id]
        (var row (await (invoke "session" {"id" id})))
        (return (:? row (Object.assign {} row {"ownerId" (. row ["owner-id"]) "beachId" (. row ["beach-id"])}) nil))))
      "save" (fn [id payload] (return (invoke "saveSession" payload)))})
    (when (== input.kind "page")
      (var result (await (pages.runPage client input.page values)))
      (return {"result" result "trace" trace "states" states "cache" caches}))
    (when (== input.kind "model")
      (var resolved (pages.resolveModel input.page input.member values (or input.payload {})))
      (var result (await (pages.runModel client input.page input.member values (or input.payload {}))))
      (return {"result" result "trace" trace "states" states "cache" caches}))
    (when (== input.kind "action")
      (var result (await (pages.runAction client input.page input.member values (or input.payload {}))))
      (return {"result" result "trace" trace "states" states "cache" caches}))
    (throw (new Error "Choose resolve, model, action or page"))
    (catch error (return {"error" {"message" error.message "code" error.code} "trace" trace "states" states "cache" caches}))
    (finally (. subscriptions (forEach (fn [unsubscribe] (unsubscribe)))))))
(defn.js resolveRefs [value outputs]
  (when (Array.isArray value) (return (. value (map (fn [v] (return (-/resolveRefs v outputs)))))))
  (when (and value (== (typeof value) "object"))
    (when (. value ["$ref"])
      (var found outputs)
      (. (. value ["$ref"]) (forEach (fn [key]
        (when (or (== found nil) (not (Object.prototype.hasOwnProperty.call found key))) (throw (new Error "Unresolved step reference")))
        (:= found (. found [key])))))
      (return found))
    (var result {})
    (. (Object.entries value) (forEach (fn [pair] (:= (. result [(. pair [0])]) (-/resolveRefs (. pair [1]) outputs)))))
    (return result))
  (return value))
(defn.js ^{:- [:async]} scenario [input]
  (var handles {})
  (try
    (when input.steps
      (var outputs {}) (var results [])
      (for:array [step input.steps]
        (var resolved (-/resolveRefs step outputs))
        (var result (await (-/execute (Object.assign {"actor" (or input.actor "alice")} resolved) handles)))
        (:= (. outputs [step.id]) result)
        (. results (push (Object.assign {"id" step.id} result))))
      (return {"steps" results}))
    (return (await (-/execute input handles)))
    (catch error (return {"error" {"message" error.message}}))
    (finally (when handles.model (handles.model.close)))))
(defrun.js main
