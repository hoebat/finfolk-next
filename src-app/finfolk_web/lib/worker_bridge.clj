(ns finfolk-web.lib.worker-bridge
  "Browser facade for worker-owned models. HTTP credentials stay in the existing SDK."
  (:require [lang.core :as l]))
(l/script :js {:require [[finfolk-web.lib.backbone :as backbone]
                        [finfolk-web.lib.operations :as registry]]})
(defn.js announce [type detail]
  (when (. globalThis ["dispatchEvent"])
    (. globalThis (dispatchEvent (new CustomEvent type {"detail" detail})))))
(defn.js error [data]
  (return (Object.assign (new Error (or (. data ["message"]) "Worker request failed.")) data)))
(defn.js post [ctx message]
  (. (. ctx ["port"]) (postMessage message)))
(defn.js request [ctx message signal]
  (when (and signal (. signal ["aborted"])) (return (Promise.reject (new DOMException "Request cancelled." "AbortError"))))
  (:= (. ctx ["sequence"]) (+ 1 (. ctx ["sequence"])))
  (var id (+ "page-" (. ctx ["sequence"])))
  (return (new Promise (fn [resolve reject]
    (var abort (fn []
      (-/post ctx {"type" "cancel" "request" id})
      (var task (. (. ctx ["pending"]) (get id)))
      (when task ((. task ["reject"]) (new DOMException "Request cancelled." "AbortError")))))
    (var finish (fn [callback value]
      (. (. ctx ["pending"]) (delete id))
      (clearTimeout timer)
      (when signal (. signal (removeEventListener "abort" abort)))
      (callback value)))
    (var timer (setTimeout (fn [] (finish reject (new Error "Application cache connection timed out."))) 45000))
    (. (. ctx ["pending"]) (set id {"message" message "resolve" (fn [v] (finish resolve v)) "reject" (fn [e] (finish reject e))}))
    (when signal (. signal (addEventListener "abort" abort {"once" true})))
    (-/post ctx (Object.assign {} message {"id" id}))))))
(defn.js markClosed [facade]
  (:= (. facade ["closed"]) true)
  (. (. facade ["snapshots"]) (clear))
  (for:iter [entry (. (. facade ["subscriptions"]) (values))]
    (try ((. entry ["callback"]) {"status" "closed"}) (catch error (console.error "Cache subscriber failed."))))
  (. (. facade ["subscriptions"]) (clear)))
(defn.js connectionReady [ctx]
  (var ready (new Promise (fn [resolve reject]
    (:= (. ctx ["resolve"]) resolve) (:= (. ctx ["reject"]) reject)
    (:= (. ctx ["timer"]) (setTimeout (fn [] (reject (new Error "SQLite worker startup timed out."))) 12000)))))
  (return (. ready (then (async (fn []
    (var result (await (-/request ctx {"type" "hello" "protocol" 1 "client" (. ctx ["client"]) "environment" (. ctx ["environment"])} nil)))
    (-/announce "finfolk:cache-status" result)
    (return result)))))))
(defn.js reconnect [ctx]
  (:= (. ctx ["connected"]) false)
  (-/announce "finfolk:cache-status" {"message" "Reconnecting application cache."})
  (for:iter [task (. (. ctx ["pending"]) (values))]
    (var message (. task ["message"]))
    (var facade (. (. ctx ["scopes"]) (get (. message ["scope"]))))
    (var spec (. registry/operations [(. message ["name"])]))
    (when (and facade spec (. spec ["write"])) (. (. facade ["blocked"]) (add (. spec ["domain"]))))
    ((. task ["reject"]) (Object.assign (new Error "Application cache restarted. Reload to confirm whether your change was saved.") {"mutationOutcomeUnknown" (not (not (and spec (. spec ["write"]))))})))
  (for:iter [controller (. (. ctx ["http"]) (values))] (. controller (abort)))
  (. (. ctx ["http"]) (clear))
  (:= (. ctx ["ready"]) (-/connectionReady ctx))
  (for:iter [facade (. (. ctx ["scopes"]) (values))]
    (when (not (. facade ["closed"]))
      (. (. facade ["snapshots"]) (clear))
      (:= (. facade ["ready"]) (. (. ctx ["ready"]) (then (async (fn []
        (await (-/request ctx {"type" "attach" "actor" (. facade ["actor"])} nil))
        (for:iter [[sub entry] (. facade ["subscriptions"])]
          (await (-/request ctx {"type" "subscribe" "scope" (. facade ["id"]) "name" (. entry ["name"]) "values" (. entry ["values"]) "subscription" sub} nil)))
        (return true)))))))))
(defn.js ^{:- [:async]} receive [ctx message]
  (var type (. message ["type"]))
  (when (== type "spawn")
    (var channel (new MessageChannel))
    (var kernel (new Worker (new URL "./workers/kernel.js" (. import.meta ["url"])) {"type" "module"}))
    (:= (. ctx ["kernel"]) kernel)
    (:= (. kernel ["onerror"]) (fn [] (-/post ctx {"type" "kernel-failed"})))
    (. kernel (postMessage {"type" "broker"} [(. channel ["port1"])]))
    (. (. ctx ["port"]) (postMessage {"type" "kernel"} [(. channel ["port2"])]))
    (return))
  (when (== type "stop-kernel") (when (. ctx ["kernel"]) (. (. ctx ["kernel"]) (terminate))) (return))
  (when (== type "restarting") (-/reconnect ctx) (return))
  (when (== type "pong") (:= (. ctx ["lastPong"]) (Date.now)) (return))
  (when (== type "ready")
    (when (and (. ctx ["connected"]) (not= (. ctx ["epoch"]) (. message ["epoch"]))) (-/reconnect ctx))
    (:= (. ctx ["epoch"]) (. message ["epoch"]))
    (:= (. ctx ["connected"]) true) (:= (. ctx ["lastPong"]) (Date.now))
    (clearTimeout (. ctx ["timer"])) ((. ctx ["resolve"]) true) (return))
  (when (== type "fatal") ((. ctx ["reject"]) (-/error (. message ["error"]))) (return))
  (when (== type "result")
    (var task (. (. ctx ["pending"]) (get (. message ["id"]))))
    (when task
      (if (. message ["error"]) ((. task ["reject"]) (-/error (. message ["error"])))
        ((. task ["resolve"]) (. message ["result"]))))
    (return))
  (when (== type "http-abort")
    (var controller (. (. ctx ["http"]) (get (. message ["id"]))))
    (when controller (. controller (abort))) (return))
  (when (== type "changed") (-/announce "finfolk:cache-changed" {}) (return))
  (when (== type "cached") (-/announce "finfolk:cache-status" {"cached" true "savedAt" (. message ["savedAt"])}) (return))
  (var facade (. (. ctx ["scopes"]) (get (. message ["scope"]))))
  (when (== type "http")
    (var controller (new AbortController))
    (. (. ctx ["http"]) (set (. message ["id"]) controller))
    (try
      (when (or (not facade) (. facade ["closed"])) (throw (new Error "Account context closed.")))
      (var result (await ((. facade ["transport"]) (. message ["name"]) (. message ["values"])
        (Object.assign {} (. message ["options"]) {"signal" (. controller ["signal"])}))))
      (-/post ctx {"type" "http-result" "id" (. message ["id"]) "result" result})
      (catch error (-/post ctx {"type" "http-result" "id" (. message ["id"])
        "error" {"message" (. error ["message"]) "name" (. error ["name"]) "status" (. error ["status"])
                 "code" (. error ["code"]) "requestId" (. error ["requestId"])}}))
      (finally (. (. ctx ["http"]) (delete (. message ["id"])))))
    (return))
  (when (not facade) (return))
  (when (or (== type "uncertain") (== type "blocked"))
    (. (. facade ["blocked"]) (add (. message ["domain"])))
    (when (== type "uncertain")
      (for:iter [task (. (. ctx ["pending"]) (values))]
        (var input (. task ["message"]))
        (var spec (. registry/operations [(. input ["name"])]))
        (when (and spec (. spec ["write"]) (== (. input ["scope"]) (. message ["scope"])) (== (. spec ["domain"]) (. message ["domain"])))
          ((. task ["reject"]) (Object.assign (new Error "Application cache restarted. Reload to confirm whether your change was saved.") {"mutationOutcomeUnknown" true})))))
    (return))
  (when (== type "invalidated")
    (. (. facade ["snapshots"]) (delete (. message ["key"])))
    (. (. facade ["revisions"]) (set (. message ["key"]) (+ 1 (or (. (. facade ["revisions"]) (get (. message ["key"]))) 0))))
    (return))
  (when (== type "cleared")
    (-/markClosed facade)
    (-/announce "finfolk:member-cleared" {"actor" (. message ["actor"])}) (return))
  (when (== type "evicted") (. (. facade ["snapshots"]) (clear)) (return))
  (when (or (== type "state") (== type "snapshot"))
    (var state (. message ["state"]))
    (if (and (not (=== (. state ["data"]) undefined)) (or (== (. state ["status"]) "ready") (. state ["cached"])))
      (. (. facade ["snapshots"]) (set (. message ["key"]) (. state ["data"])))
      (. (. facade ["snapshots"]) (delete (. message ["key"]))))
    (var entry (. (. facade ["subscriptions"]) (get (. message ["subscription"]))))
    (when entry (try ((. entry ["callback"]) state) (catch error (console.error "Cache subscriber failed."))))
    (when (. state ["cached"]) (-/announce "finfolk:cache-status" {"cached" true "savedAt" (. state ["savedAt"])}))))

(defn.js createScope [ctx actor transport]
  (var facade {"actor" actor "transport" transport "snapshots" (new Map) "revisions" (new Map) "subscriptions" (new Map) "blocked" (new Set) "closed" false})
  (var ready (. (. ctx ["ready"]) (then (fn [] (return (-/request ctx {"type" "attach" "actor" actor} nil))))))
  (:= ready (. ready (then (async (fn [id]
    (:= (. facade ["id"]) id)
    (. (. ctx ["scopes"]) (set id facade))
    (await (-/request ctx {"type" "recover" "scope" id} nil))
    (return true))))))
  (:= (. facade ["ready"]) (. ready (catch (fn [error]
    (:= (. facade ["local"]) (backbone/createBackbone actor
      (fn [name values options] (return ((. facade ["transport"]) name values options)))))
    (-/announce "finfolk:cache-status" {"mode" "unavailable" "message" "Application storage unavailable. Using the online memory cache."})
    (return true)))))
  (var api
    {"actor" actor "kind" "xt.substrate+xt.db+sqlite" "ready" (. facade ["ready"])
     "supports" (fn [name] (return (not (not (. registry/operations [name])))))
     "setTransport" (fn [transport] (:= (. facade ["transport"]) transport))
     "call" (async (fn [name values options]
       (when (. facade ["closed"]) (throw (new Error "Account context closed.")))
       (var spec (registry/operation name))
       (when (and (. spec ["write"]) (. (. facade ["blocked"]) (has (. spec ["domain"]))))
         (throw (new Error "Reload before making another change: confirm whether the previous change was saved.")))
       (await (. facade ["ready"]))
       (when (. facade ["closed"]) (throw (new Error "Account context closed.")))
       (when (and (. spec ["write"]) (. (. facade ["blocked"]) (has (. spec ["domain"]))))
         (throw (new Error "Reload before making another change: confirm whether the previous change was saved.")))
       (:= values (or values {})) (:= options (or options {}))
       (var key (+ name ":" (backbone/stableKey values)))
       (var revision (or (. (. facade ["revisions"]) (get key)) 0))
       (when (. facade ["local"]) (return (. (. facade ["local"]) (call name values options))))
       (var result (await (-/request ctx {"type" "call" "scope" (. facade ["id"]) "name" name "values" values
          "options" {"idempotencyKey" (. options ["idempotencyKey"])}} (. options ["signal"]))))
       (when (. facade ["closed"]) (throw (new Error "Account context closed.")))
       (when (and (not (. (registry/operation name) ["write"])) (== revision (or (. (. facade ["revisions"]) (get key)) 0)))
         (. (. facade ["snapshots"]) (set (+ name ":" (backbone/stableKey values)) result)))
       (return result)))
     "read" (fn [name values]
       (when (. facade ["closed"]) (return undefined))
       (when (. facade ["local"]) (return (. (. facade ["local"]) (read name values))))
       (return (. (. facade ["snapshots"]) (get (+ name ":" (backbone/stableKey (or values {})))))))
     "subscribe" (fn [name values callback]
       (:= values (or values {}))
       (var sub (+ "sub-" (Math.random))) (var stopped false) (var localStop nil)
       (. (. facade ["subscriptions"]) (set sub {"callback" callback "name" name "values" values}))
       (callback {"status" "loading"})
       (. (. facade ["ready"]) (then (fn []
         (when (or stopped (. facade ["closed"])) (return))
         (if (. facade ["local"])
           (:= localStop (. (. facade ["local"]) (subscribe name values callback)))
           (return (-/request ctx {"type" "subscribe" "scope" (. facade ["id"]) "name" name "values" values "subscription" sub} nil)))))
         (catch (fn [error] (when (not stopped) (callback {"status" "error" "error" error})))))
       (return (fn []
         (:= stopped true) (. (. facade ["subscriptions"]) (delete sub))
         (when localStop (localStop))
         (when (and (. facade ["id"]) (not (. facade ["closed"])))
           (. (-/request ctx {"type" "unsubscribe" "scope" (. facade ["id"]) "subscription" sub} nil) (catch (fn [])))))))
     "invalidate" (async (fn [domains]
       (await (. facade ["ready"]))
       (. (. facade ["snapshots"]) (clear))
       (when (. facade ["closed"]) (return))
       (when (. facade ["local"]) (return (. (. facade ["local"]) (invalidate domains))))
       (return (-/request ctx {"type" "invalidate" "scope" (. facade ["id"]) "domains" domains} nil))))
     "clearCache" (async (fn []
       (await (. facade ["ready"])) (. (. facade ["snapshots"]) (clear))
       (when (. facade ["local"]) (return (. (. facade ["local"]) (clearCache))))
       (return (-/request ctx {"type" "clear-cache" "scope" (. facade ["id"])} nil))))
     "close" (fn []
       (when (. facade ["closed"]) (return (Promise.resolve)))
       (-/markClosed facade)
       (return (. (. facade ["ready"]) (then (fn []
         (if (. facade ["local"])
           (return (. (. facade ["local"]) (close)))
           (return (-/request ctx {"type" "purge" "scope" (. facade ["id"])} nil))))))))})
  (return api))

(defn.js createWorkerBridge [config]
  (when (or (== (typeof Worker) "undefined") (== (typeof MessageChannel) "undefined")) (return nil))
  (var ctx {"scopes" (new Map) "pending" (new Map) "http" (new Map) "sequence" 0
            "client" (. crypto (randomUUID)) "environment" (JSON.stringify [(. config ["authUrl"]) (. config ["apiUrl"])])})
  (var channel (new MessageChannel))
  (var worker nil)
  (var shared (not= (typeof SharedWorker) "undefined"))
  (if shared
    (do (:= worker (new SharedWorker (new URL "./workers/finfolk.sharedworker.js?protocol=2" (. import.meta ["url"])) {"type" "module" "name" "finfolk-next-sqlite-v2"}))
        (:= (. ctx ["port"]) (. worker ["port"])))
    (do (:= worker (new Worker (new URL "./workers/kernel.js" (. import.meta ["url"])) {"type" "module"}))
        (:= (. ctx ["port"]) (. channel ["port1"]))
        (. worker (postMessage {"type" "connect" "ephemeral" true} [(. channel ["port2"])]))))
  (:= (. ctx ["ready"]) (-/connectionReady ctx))
  (:= (. ctx ["worker"]) worker)
  (:= (. worker ["onerror"]) (fn [] ((. ctx ["reject"]) (new Error "SQLite worker could not start."))))
  (. (. ctx ["port"]) (addEventListener "message" (fn [event] (-/receive ctx (. event ["data"])))))
  (. (. ctx ["port"]) (start))
  (. (. ctx ["ready"]) (catch (fn [])))
  (var heartbeat nil)
  (when (. globalThis ["addEventListener"])
    (when shared
      (:= heartbeat (setInterval (fn []
        (when (and (. ctx ["connected"]) (> (- (Date.now) (. ctx ["lastPong"])) 8000))
          (:= (. ctx ["connected"]) false)
          (try (-/post ctx {"type" "detach"}) (. (. ctx ["port"]) (close)) (catch error nil))
          (var replacement (new SharedWorker (new URL "./workers/finfolk.sharedworker.js?protocol=2" (. import.meta ["url"])) {"type" "module" "name" "finfolk-next-sqlite-v2"}))
          (:= (. ctx ["worker"]) replacement) (:= (. ctx ["port"]) (. replacement ["port"]))
          (-/reconnect ctx)
          (. (. ctx ["port"]) (addEventListener "message" (fn [event] (-/receive ctx (. event ["data"])))))
          (. (. ctx ["port"]) (start)))
        (-/post ctx {"type" "ping"})) 2000))
      (. globalThis (addEventListener "pageshow" (fn [] (-/post ctx {"type" "ping"})))))
    (. globalThis (addEventListener "pagehide" (fn [event]
      (-/post ctx {"type" (:? (. event ["persisted"]) "yield" "detach")})
      (when (not (. event ["persisted"])) (clearInterval heartbeat))
      (when (. ctx ["kernel"]) (. (. ctx ["kernel"]) (terminate)))))))
  (return {"open" (fn [actor transport] (return (-/createScope ctx actor transport)))
           "health" (fn [] (return (-/request ctx {"type" "coordinator"} nil)))
           "ready" (. ctx ["ready"])
           "stats" (async (fn [] (await (. ctx ["ready"])) (return (-/request ctx {"type" "stats"} nil))))
           "evict" (async (fn [ids] (await (. ctx ["ready"])) (return (-/request ctx {"type" "evict" "ids" ids} nil))))}))
