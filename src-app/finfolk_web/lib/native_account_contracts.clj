(ns finfolk-web.lib.native-account-contracts
  (:require [lang.core :as l] [finfolkdb.schema.account-contracts :as contracts]))
(l/script :js)
(def.js operations (@! contracts/OPERATIONS))
(defn.js compactRequest [value]
  (when (Array.isArray value) (return (. value (map -/compactRequest))))
  (when (and value (== (typeof value) "object"))
    (var pairs [])
    (for:array [pair (Object.entries value)]
      (when (not (=== (. pair [1]) undefined))
        (. pairs (push [(. pair [0]) (-/compactRequest (. pair [1]))]))))
    (return (Object.fromEntries pairs)))
  (return value))
(defn.js validate [schema value (:= path "input")]
  (when (Array.isArray schema.type)
    (var found (. schema.type (some (fn [type]
      (try (-/validate (Object.assign {} schema {"type" type}) value path) (return true)
        (catch error (return false)))))))
    (when (not found) (throw (new Error (+ "Invalid " path))))
    (return value))
  (var valid true)
  (cond (== schema.type "null") (:= valid (=== value nil))
        (== schema.type "string") (:= valid (== (typeof value) "string"))
        (== schema.type "boolean") (:= valid (== (typeof value) "boolean"))
        (or (== schema.type "number") (== schema.type "integer"))
        (:= valid (and (Number.isFinite value) (or (== schema.type "number") (Number.isInteger value))))
        (== schema.type "array") (:= valid (Array.isArray value))
        (== schema.type "object") (:= valid (and value (== (typeof value) "object") (not (Array.isArray value))))
        :else (throw (new Error "Unsupported account schema")))
  (when (not valid) (throw (new Error (+ "Invalid " path))))
  (when (and schema.enum (not (. schema.enum (includes value)))) (throw (new Error (+ "Invalid " path))))
  (when (and (== schema.format "uuid")
    (not (. (new RegExp "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$") (test value))))
    (throw (new Error (+ "Invalid " path))))
  (when (and (== schema.format "date")
    (not (. (new RegExp "^[0-9]{4}-[0-9]{2}-[0-9]{2}$") (test value))))
    (throw (new Error (+ "Invalid " path))))
  (when (== schema.type "array")
    (. value (forEach (fn [item index] (-/validate schema.items item (+ path "." index))))))
  (when (== schema.type "object")
    (. (or schema.required []) (forEach (fn [key]
      (when (not (Object.prototype.hasOwnProperty.call value key)) (throw (new Error (+ "Missing " path "." key)))))))
    (. (Object.entries value) (forEach (fn [pair]
      (var key (. pair [0])) (var child (. (or schema.properties {}) [key]))
      (when (and (not child) (=== schema.additionalProperties false))
        (throw (new Error (+ "Unknown " path "." key))))
      (when child (-/validate child (. pair [1]) (+ path "." key)))))))
  (return value))
