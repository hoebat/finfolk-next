(ns finfolk-web.lib.browser
  "Configuration and public HTTP adapter for the existing DOM application."
  (:require [lang.core :as l]))
(l/script :js)
(def.js Configuration {"promise" nil})
(defn.js ^{:- [:async]} appConfiguration []
  (when (not (. -/Configuration ["promise"]))
    (var url (new URL "./neon-config.json" (. import.meta ["url"])))
    (. (. url ["searchParams"]) (set "v" (. import.meta ["url"])))
    (:= (. -/Configuration ["promise"])
        (. (fetch url
                  {"cache" "no-cache" "signal" (AbortSignal.timeout 5000)})
           (catch (fn [_]
                    (return (fetch (new URL "./neon-config.json" (. import.meta ["url"]))
                                   {"cache" "no-cache" "signal" (AbortSignal.timeout 5000)}))))
           (then (fn [response]
                   (when (not (. response ["ok"])) (throw (new Error "Account configuration unavailable.")))
                   (return (. response (json))))))))
  (try (return (await (. -/Configuration ["promise"])))
       (catch error
         (:= (. -/Configuration ["promise"]) (Promise.resolve {"backbone" false}))
         (return {"backbone" false}))))
(defn.js ^{:- [:async]} httpOperation [config name input options]
  (:= options (or options {}))
  (var runtime (await (import "./next-backbone.js")))
  (var spec (. runtime ["operations"] [name]))
  (when (or (not spec) (. spec ["auth"]) (not= (. spec ["transport"]) "rest"))
    (throw (new Error "Invalid public operation.")))
  (var path (. (. spec ["path"]) (replace (new RegExp ":([a-z]+)" "g")
                                        (fn [_ key] (return (encodeURIComponent (. input [key])))))))
  (var base (. config ["apiUrl"]))
  (var url (new URL (. path (replace (new RegExp "^/") "")) (:? (. base (endsWith "/")) base (+ base "/"))))
  (when (not (. spec ["write"]))
    (for:array [key (Object.keys input)]
      (var value (. input [key]))
      (when (and (not= value nil) (not (. (. spec ["path"]) (includes (+ ":" key)))))
        (. (. url ["searchParams"]) (set key (String value))))))
  (var init {"method" (. spec ["method"]) "cache" "no-store" "referrerPolicy" "no-referrer" "signal" (. options ["signal"])})
  (when (. spec ["write"])
    (var body (Object.assign {} input))
    (. (Object.keys body) (forEach (fn [key]
      (when (. (. spec ["path"]) (includes (+ ":" key))) (delete (. body [key]))))))
    (Object.assign init {"headers" {"Content-Type" "application/json"} "body" (JSON.stringify body) "keepalive" (== name "publicReferral")}))
  (var response (await (fetch url init)))
  (var result (await (. response (json))))
  (when (not (. response ["ok"]))
    (var error (. result ["error"]))
    (throw (Object.assign (new Error (or (and error (. error ["message"])) error "Request failed.")) {"status" (. response ["status"])})))
  (return result))
(defn.js ^{:- [:async]} applicationBackbone [config]
  (when config (:= (. -/Configuration ["promise"]) (Promise.resolve config)))
  (:= config (or config (await (-/appConfiguration))))
  (when (not (. config ["backbone"])) (return nil))
  (var runtime (await (import "./next-backbone.js")))
  (var app (. runtime (createApplicationBackbone config)))
  (. app (setPublicTransport (fn [name input options] (return (-/httpOperation config name input options)))))
  (return app))
(defn.js ^{:- [:async]} publicOperation [name input apiUrl legacy options]
  (when (not (. -/Configuration ["promise"])) (return (legacy)))
  (var config (await (-/appConfiguration)))
  (when (not (. config ["backbone"])) (return (legacy)))
  (when (and apiUrl (not= (. (new URL apiUrl) ["origin"]) (. (new URL (. config ["apiUrl"])) ["origin"])))
    (throw (new Error "Public API environment mismatch.")))
  (var app (await (-/applicationBackbone config)))
  (return (. (. app ["public"]) (call name input (or options {})))))
